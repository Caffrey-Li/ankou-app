fn main() {
    let verify = std::path::Path::new("capabilities/verify.json");
    if verify.exists() {
        std::fs::remove_file(verify).ok();
    }
    let generated = std::path::Path::new("permissions/autogenerated");
    for name in ["verify_enabled.toml", "verify_set.toml"] {
        let path = generated.join(name);
        if path.exists() {
            std::fs::remove_file(path).ok();
        }
    }
    const COMMANDS: &[&str] = &[
        "list_grants",
        "revoke",
        "get_settings",
        "set_settings",
        "save_deepseek_key",
        "delete_deepseek_key",
        "deepseek_key_saved",
        "clear_history",
        "discover_tools",
        "complete_setup",
        "get_usage",
        "refresh_usage",
        "set_capability",
        "list_conversations",
        "prepare_handoff",
        "begin_summary",
        "send_summary",
        "prepare_deeplink",
        "place_deeplink",
        "export_handoff",
        "organize_handoff",
        "tool_icons",
        "scan_space",
        "cancel_scan",
        "prepare_cleanup",
        "run_cleanup",
        "open_privacy_settings",
        "send_notice",
        "tray_action",
        "check_update",
        "install_update",
    ];
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(COMMANDS)),
    )
    .expect("生成 Tauri 权限失败");
}
